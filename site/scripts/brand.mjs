// The site's identity files, derived from public/logo.svg and brand/brand.json (SSOT): the
// icons, favicon.ico, og-image and web manifest in public/ are never edited by hand.
//
//   node scripts/brand.mjs           regenerate every derived file and brand/derived.lock
//   node scripts/brand.mjs --check   fail if any derived file differs from what this produces,
//                                    or if an input changed since the files were generated
//
// Rasterised with @resvg/resvg-js (pinned exactly): pure Rust, no system fonts and no browser,
// so the output depends only on the inputs below. Text uses the vendored Inter (brand/fonts,
// OFL): the site's own stack is system-ui, which differs per device, so it cannot be rendered
// reproducibly.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { Resvg } from '@resvg/resvg-js';
import { outputs } from './brand/compose.mjs';
import { compare, icoEntries, icoPack } from './brand/png.mjs';

const site = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const at = (...p) => path.join(site, ...p);
const FONTS = [at('brand/fonts/Inter-Regular.ttf'), at('brand/fonts/Inter-Bold.ttf')];
const LOCK = at('brand/derived.lock');
/** Anti-aliasing may round a channel differently on another CPU; an edit moves far more. */
const TOLERANCE = 3;
const RESVG_VERSION = createRequire(import.meta.url)('@resvg/resvg-js/package.json').version;

const INPUTS = [at('public/logo.svg'), at('brand/brand.json'), ...FONTS, fileURLToPath(import.meta.url), at('scripts/brand/compose.mjs'), at('scripts/brand/png.mjs')];

function inputsDigest() {
  const h = createHash('sha3-256');
  h.update(`resvg ${RESVG_VERSION}\n`);
  for (const file of INPUTS) h.update(`${path.relative(site, file)}\n`).update(readFileSync(file));
  return h.digest('hex');
}

function render(svg) {
  const resvg = new Resvg(svg, { font: { fontFiles: FONTS, loadSystemFonts: false, defaultFontFamily: 'Inter' } });
  return resvg.render().asPng();
}

function build() {
  const brand = JSON.parse(readFileSync(at('brand/brand.json'), 'utf8'));
  return outputs(readFileSync(at('public/logo.svg'), 'utf8'), brand).map((o) => {
    if (o.kind === 'text') return { ...o, bytes: Buffer.from(o.text) };
    if (o.kind === 'png') return { ...o, bytes: render(o.svg) };
    return { ...o, bytes: icoPack(o.svgs.map(render)) };
  });
}

function lockText(digest) {
  return `${JSON.stringify({ inputs_sha3_256: digest, resvg: RESVG_VERSION }, null, 2)}\n`;
}

/** Problems with one committed file against its regenerated bytes; empty when it matches. */
function drift(o, committed) {
  if (o.kind === 'text') return Buffer.compare(o.bytes, committed) === 0 ? [] : [`${o.file} differs from what the script writes`];
  const pairs = o.kind === 'png' ? [[o.bytes, committed]] : icoPairs(o.bytes, committed, o.file);
  return pairs.flatMap(([want, got], i) => {
    const r = compare(want, got, TOLERANCE);
    if (!r.exact && r.close) console.log(`brand: ${o.file}${pairs.length > 1 ? `[${i}]` : ''} matches within ±${TOLERANCE} (max ${r.max}), not byte for byte`);
    return r.close ? [] : [`${o.file}${pairs.length > 1 ? `[${i}]` : ''} differs (${(r.share * 100).toFixed(2)}% of channels, max ${r.max})`];
  });
}

function icoPairs(want, got, file) {
  const [w, g] = [icoEntries(want), icoEntries(got)];
  if (w.length !== g.length) throw new Error(`${file} holds ${g.length} images, the script writes ${w.length}`);
  return w.map((e, i) => [e.image, g[i].image]);
}

function check() {
  const problems = [];
  const lock = (() => {
    try {
      return readFileSync(LOCK, 'utf8');
    } catch (e) {
      return `missing: ${e.message}`;
    }
  })();
  if (lock !== lockText(inputsDigest())) problems.push('brand/derived.lock: an input changed since the files were generated (run `npm run brand`)');
  for (const o of build()) {
    let committed;
    try {
      committed = readFileSync(at('public', o.file));
    } catch (e) {
      problems.push(`public/${o.file}: ${e.message}`);
      continue;
    }
    try {
      problems.push(...drift(o, committed).map((p) => `public/${p}`));
    } catch (e) {
      problems.push(`public/${o.file}: ${e.message}`);
    }
  }
  if (problems.length) {
    console.error(`brand --check: FAIL\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.log('brand --check: PASS (every derived file matches public/logo.svg and brand/brand.json)');
}

function write() {
  for (const o of build()) {
    writeFileSync(at('public', o.file), o.bytes);
    console.log(`brand: public/${o.file} (${o.bytes.length} bytes)`);
  }
  writeFileSync(LOCK, lockText(inputsDigest()));
}

const args = process.argv.slice(2);
if (args.length === 1 && args[0] === '--check') check();
else if (args.length === 0) write();
else {
  console.error('usage: node scripts/brand.mjs [--check]');
  process.exit(2);
}
